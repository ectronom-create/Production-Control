-- 1. USERS TABLE (جدول المستخدمين والفرق)
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  company_id TEXT DEFAULT '',
  email TEXT DEFAULT '',
  phone TEXT DEFAULT '',
  access TEXT NOT NULL DEFAULT 'supervisor', -- 'admin', 'supervisor', 'viewer'
  team_name TEXT DEFAULT '',                 -- اسم الفريق
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- If users table already exists, make sure team_name column exists
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS team_name TEXT DEFAULT '';

-- 2. PRODUCTION RECORDS / FPY REPORTS TABLE (جدول سجلات الإنتاج والجودة)
CREATE TABLE IF NOT EXISTS public.production_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  product TEXT DEFAULT 'Unknown',
  target INTEGER DEFAULT 320,
  overall_fpy NUMERIC,
  total_boards INTEGER DEFAULT 0,
  achieved INTEGER DEFAULT 0,
  updated_fw_qty INTEGER DEFAULT 0,          -- كمية الفيرموير المحدث يدوياً
  entered_by TEXT DEFAULT '',                -- اسم الشخص المدخل
  team_name TEXT DEFAULT '',                 -- اسم الفريق
  stations JSONB DEFAULT '[]'::jsonb,
  defects JSONB DEFAULT '[]'::jsonb,
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Backward compatibility view if any query targets fpy_reports
CREATE OR REPLACE VIEW public.fpy_reports AS 
SELECT * FROM public.production_records;

-- 3. STOPPAGES / DOWNTIME TABLE (جدول التوقفات)
CREATE TABLE IF NOT EXISTS public.stoppages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage_id TEXT NOT NULL,
  supervisor_id TEXT DEFAULT '',
  stopped_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  resumed_at TIMESTAMPTZ,
  reason_code TEXT DEFAULT '',
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. KIT METERS TABLE (جدول عدد الكيت والباتشات)
CREATE TABLE IF NOT EXISTS public.kit_meters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_number TEXT NOT NULL,
  kit_quantity INTEGER NOT NULL DEFAULT 0,
  date TEXT NOT NULL,
  product_name TEXT NOT NULL DEFAULT 'Three Phase', -- 'Three Phase', 'Single Phase'
  notes TEXT DEFAULT '',
  created_by TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. SHIPMENT BATCHES (دفعات الشحن إلى نماء أو الميدان)
CREATE TABLE IF NOT EXISTS public.shipment_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_name TEXT NOT NULL,
  file_name TEXT DEFAULT '',
  shipment_date TEXT NOT NULL,
  total_meters INTEGER NOT NULL DEFAULT 0,
  product_type TEXT NOT NULL DEFAULT 'Three Phase', -- 'Three Phase', 'Single Phase'
  destination TEXT NOT NULL DEFAULT 'Nama / Field',
  notes TEXT DEFAULT '',
  uploaded_by TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. BATCH METER RECORDS (سجلات تفاصيل كل عداد تم شحنه بجميع الحقول الـ 13)
CREATE TABLE IF NOT EXISTS public.batch_meter_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT REFERENCES public.shipment_batches(id) ON DELETE CASCADE,
  batch_name TEXT NOT NULL,
  device_pallet_number TEXT DEFAULT '',
  device_box_number TEXT DEFAULT '',
  factory_serial_number TEXT DEFAULT '',
  date_of_manufactory TEXT DEFAULT '',
  hardware_version TEXT DEFAULT '',
  lot_number TEXT DEFAULT '',
  serial_number TEXT NOT NULL,
  logic_device_name TEXT DEFAULT '',
  app_software_version TEXT DEFAULT '',
  legal_software_version TEXT DEFAULT '',
  module_software_version TEXT DEFAULT '',
  module_imei TEXT DEFAULT '',
  module_iccid TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_batch_meter_sn ON public.batch_meter_records(serial_number);
CREATE INDEX IF NOT EXISTS idx_batch_meter_batch_id ON public.batch_meter_records(batch_id);
CREATE INDEX IF NOT EXISTS idx_batch_meter_pallet ON public.batch_meter_records(device_pallet_number);
CREATE INDEX IF NOT EXISTS idx_batch_meter_box ON public.batch_meter_records(device_box_number);
CREATE INDEX IF NOT EXISTS idx_batch_meter_imei ON public.batch_meter_records(module_imei);
CREATE INDEX IF NOT EXISTS idx_batch_meter_iccid ON public.batch_meter_records(module_iccid);

-- 7. BATCH FIRMWARE UPDATE TARGETS (سيريالات العدادات المطلوب تحديثها لكل باتش)
CREATE TABLE IF NOT EXISTS public.batch_fw_targets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_name TEXT NOT NULL,
  serial_number TEXT NOT NULL,
  sn_suffix TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_batch_fw_targets_batch ON public.batch_fw_targets(batch_name);
CREATE INDEX IF NOT EXISTS idx_batch_fw_targets_sn ON public.batch_fw_targets(serial_number);
CREATE INDEX IF NOT EXISTS idx_batch_fw_targets_suffix ON public.batch_fw_targets(sn_suffix);

-- 8. DEFECTIVE METERS MANAGEMENT & REWORK TRACKING (جدول تنظيم العدادات المعطلة وتتبع دورات الإصلاح)
CREATE TABLE IF NOT EXISTS public.defective_meters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  serial_number TEXT NOT NULL,
  stage TEXT NOT NULL,                          -- Assembly, Insulation, RF, Calibration, Multi-Test, Perso, Packaging
  defect_code TEXT NOT NULL,                    -- e.g. -640, E-101
  logged_by TEXT DEFAULT '',                    -- اسم المشرف أو المدخل
  logged_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  status TEXT NOT NULL DEFAULT 'UNDER_INSPECTION', -- 'UNDER_INSPECTION', 'IN_REPAIR', 'RETURNED_TO_LINE', 'SCRAPPED_KO'
  entry_count INTEGER NOT NULL DEFAULT 1,       -- كم مرة دخل العداد معطلاً
  return_count INTEGER NOT NULL DEFAULT 0,      -- كم مرة خرج بعد الإصلاح وعاد للإنتاج
  repair_notes TEXT DEFAULT '',                 -- الإجراء التصحيحي وتفاصيل الإصلاح
  repaired_by TEXT DEFAULT '',                  -- اسم الفني القائم بالإصلاح
  repaired_at TIMESTAMPTZ,                      -- وقت الإصلاح
  return_destination TEXT DEFAULT '',           -- محطة العودة للخط
  notes TEXT DEFAULT '',
  history JSONB DEFAULT '[]'::jsonb,            -- سجل كامل للحركات السابقة
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_defective_meters_sn ON public.defective_meters(serial_number);
CREATE INDEX IF NOT EXISTS idx_defective_meters_stage ON public.defective_meters(stage);
CREATE INDEX IF NOT EXISTS idx_defective_meters_status ON public.defective_meters(status);
CREATE INDEX IF NOT EXISTS idx_defective_meters_code ON public.defective_meters(defect_code);

-- 9. PRE-PRODUCTION CHECKLISTS TABLE (جدول مهام التحقق قبل بدء الإنتاج)
CREATE TABLE IF NOT EXISTS public.pre_production_checklists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_no TEXT DEFAULT 'PSM-CHK-06-2026',
  rev TEXT DEFAULT '00',
  date TEXT NOT NULL,
  shift TEXT NOT NULL,                          -- Day, Night
  supervisor TEXT DEFAULT '',
  status TEXT NOT NULL,                         -- LINE_CLEARED_PASS, CRITICAL_BLOCKER, IN_PROGRESS, etc.
  readiness_pct INTEGER DEFAULT 0,
  passed_count INTEGER DEFAULT 0,
  failed_count INTEGER DEFAULT 0,
  total_items INTEGER DEFAULT 7,
  item_details JSONB DEFAULT '{}'::jsonb,
  general_notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_pre_production_date ON public.pre_production_checklists(date);
CREATE INDEX IF NOT EXISTS idx_pre_production_shift ON public.pre_production_checklists(shift);

-- 10. ROW LEVEL SECURITY (RLS) POLICIES
-- Allow anon client to read and write records
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.production_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stoppages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kit_meters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.shipment_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.batch_meter_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.batch_fw_targets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.defective_meters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pre_production_checklists ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anon full access on defective_meters" ON public.defective_meters;
CREATE POLICY "Anon full access on defective_meters" ON public.defective_meters 
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon full access on pre_production_checklists" ON public.pre_production_checklists;
CREATE POLICY "Anon full access on pre_production_checklists" ON public.pre_production_checklists 
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

GRANT ALL ON TABLE public.defective_meters TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.pre_production_checklists TO anon, authenticated, service_role;

DROP POLICY IF EXISTS "Anon full access on users" ON public.users;
CREATE POLICY "Anon full access on users" ON public.users 
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon full access on production_records" ON public.production_records;
CREATE POLICY "Anon full access on production_records" ON public.production_records 
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon full access on stoppages" ON public.stoppages;
CREATE POLICY "Anon full access on stoppages" ON public.stoppages 
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon full access on kit_meters" ON public.kit_meters;
CREATE POLICY "Anon full access on kit_meters" ON public.kit_meters 
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon full access on shipment_batches" ON public.shipment_batches;
CREATE POLICY "Anon full access on shipment_batches" ON public.shipment_batches 
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon full access on batch_meter_records" ON public.batch_meter_records;
CREATE POLICY "Anon full access on batch_meter_records" ON public.batch_meter_records 
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Anon full access on batch_fw_targets" ON public.batch_fw_targets;
CREATE POLICY "Anon full access on batch_fw_targets" ON public.batch_fw_targets 
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

